# -*- coding: utf-8 -*-
"""챕터 C~F 치환 규칙 생성.

  C 26 입고 (29~41) : A 복제 → 입출고대 C/V #11 → C/V #13, 트랙 22/21 → 26/25
  D 24 출고 (42~54) : B 복제 → 입출고대 C/V #11 → C/V #12, 트랙 21/22 → 23/24
  E 30 입고 (55~67) : A 복제, ①구간은 C/V #15 손그림(원본 14,15) 이라 제목만
  F 29 출고 (68~80) : B 복제, ④구간은 C/V #14 손그림(원본 12,13) 이라 제목만

  주소 근거 : PlcAddressMap.xml (scen.json). PPT 원본 표기 규칙에 맞춰
    · M 비트  : Mxxx.y %MXnnn
    · D 워드  : Dxxxx → %DWnnn(%DBmmm)
    · R 트래킹: 문서표기 Rxxxx 와 10진 바이트 %RBnnn (원본 PPT 규칙)
"""
import io, json

def mb(a):   return "M%03d.%d" % (a // 16, a % 16)
def mx(a):   return "%%MX%d" % a

# ── C/V 별 주소 (XML 계산식 그대로) ────────────────────────────────────
def cv(no):
    ev  = 256 + (no - 1) * 32      # Event base
    ack = 1280 + (no - 1) * 16     # Ack base
    dw  = 480 + (no - 1)           # Direction word
    rdoc = (no - 1) * 10           # Tracking 문서표기 워드
    return {
        "ev": ev, "ack": ack, "dw": dw, "rdoc": rdoc,
        "UC1": ev + 1, "LC1": ev + 2, "UC2": ev + 3, "LC2": ev + 4, "WO": ev + 6,
        "P0": ev + 16, "P1": ev + 17, "P2": ev + 18,
        "UC1A": ack + 1, "LC1A": ack + 2, "UC2A": ack + 3, "LC2A": ack + 4,
    }

rules = []
def R(slide, subs): rules.append({"slide": slide, "subs": subs})

def cv_addr_subs(src, dst):
    """C/V 번호가 바뀔 때 M비트·D워드 표기를 전부 치환"""
    a, b = cv(src), cv(dst)
    out = []
    for k in ("UC1", "LC1", "UC2", "LC2", "WO", "P0", "P1", "P2",
              "UC1A", "LC1A", "UC2A", "LC2A"):
        out.append([mx(a[k]), mx(b[k])])
        out.append([mb(a[k]), mb(b[k])])
    # 방향 워드 : Dxxxx → %DWnnn(%DBmmm)
    out.append(["D0%d" % (300 + src - 1), "D0%d" % (300 + dst - 1)])
    out.append(["%%DW%d(%%DB%d)" % (a["dw"], a["dw"] * 2),
                "%%DW%d(%%DB%d)" % (b["dw"], b["dw"] * 2)])
    out.append(["%%DW%d" % a["dw"], "%%DW%d" % b["dw"]])
    out.append(["%%DB%d" % (a["dw"] * 2), "%%DB%d" % (b["dw"] * 2)])
    # 트래킹 : 문서표기 R00xx ~ / 10진 %RBnnn
    for slot in (0, 1):
        rs, rd = a["rdoc"] + slot * 2, b["rdoc"] + slot * 2
        out.append(["R%04d~R%04d %%RB%d~%%RB%d" % (rs, rs + 1, rs * 2, rs * 2 + 2),
                    "R%04d~R%04d %%RB%d~%%RB%d" % (rd, rd + 1, rd * 2, rd * 2 + 2)])
        out.append(["R%04d" % rs, "R%04d" % rd])
        out.append(["%%RB%d" % (rs * 2), "%%RB%d" % (rd * 2)])
    return out

# ══ 챕터 C : 26 입고 (29~41) ═════════════════════════════════════════
#   29 개요 / 30,31 ①C/V#13 / 32,33 ②RGV / 34,35 ③통로 / 36,37 ④S/C / 38~41 병기
C_TITLE = [
    ["입출고대 #22 → #21, C/V #11", "26 입고대 #26 → #25, C/V #13"],
    ["입출고대 ", "26 입고대 "],
]
for sl in (30, 31):
    R(sl, C_TITLE + cv_addr_subs(11, 13) + [
        ["#22", "#26"], ["#21", "#25"], ["C/V #11", "C/V #13"],
        ["22", "26"], ["21", "25"],
    ])
for sl in (32, 33):
    R(sl, [
        ["#21 → C/V #2 #3", "#25 → C/V #2 #3"],
        ["=00/00/21", "=00/00/25"],
        ["RGV : #21", "RGV : #25"],
        ["#21", "#25"],
    ])
for sl in (34, 35, 36, 37):
    R(sl, [["(S/C #1  입고작업", "(26 입고대 → S/C #1  입고작업"]])

# ══ 챕터 D : 24 출고 (42~54) ═════════════════════════════════════════
#   42 개요 / 43,44 ①S/C / 45,46 ②통로 / 47,48 ③RGV / 49,50 ④C/V#12 / 51~54 병기
for sl in (43, 44, 45, 46):
    R(sl, [["(S/C #1 출고작업", "(S/C #1 → 24 출고대  출고작업"]])
for sl in (47, 48):
    R(sl, [
        ["C/V #2 #3 → #21", "C/V #2 #3 → #23"],
        ["To : D0373(%DW851)=00/00/21", "To : D0373(%DW851)=00/00/23"],
        ["입출고대 #21 로 주행", "24 출고대 #23 로 주행"],
        ["#21", "#23"],
    ])
for sl in (49, 50):
    R(sl, cv_addr_subs(11, 12) + [
        ["입출고대 #21 → #22, C/V #11", "24 출고대 #23 → #24, C/V #12"],
        ["입출고대", "24 출고대"],
        ["#21", "#23"], ["#22", "#24"], ["C/V #11", "C/V #12"],
        ["21", "23"], ["22", "24"],
    ])

# ══ 챕터 E : 30 입고 (55~67) ═════════════════════════════════════════
#   55 개요 / 56,57 ①C/V#15(원본 14,15) / 58,59 ②RGV / 60,61 ③통로 / 62,63 ④S/C
for sl in (56, 57):
    R(sl, [
        ["( 입고  : C/V # 15 ", "(30 입고대 → S/C #1  입고작업 ① : C/V #15 "],
        ["피킹존 입고(동시에 출고 C/V 존재함))", "30 → #32 → #31)"],
    ])
for sl in (58, 59):
    R(sl, [
        ["#21 → C/V #2 #3", "#31 → C/V #2 #3"],
        ["=00/00/21", "=00/00/31"],
        ["RGV : #21", "RGV : #31"],
        ["#21", "#31"],
        ["(S/C #1  입고작업", "(30 입고대 → S/C #1  입고작업"],
    ])
for sl in (60, 61, 62, 63):
    R(sl, [["(S/C #1  입고작업", "(30 입고대 → S/C #1  입고작업"]])

# ══ 챕터 F : 29 출고 (68~80) ═════════════════════════════════════════
#   68 개요 / 69,70 ①S/C / 71,72 ②통로 / 73,74 ③RGV / 75,76 ④C/V#14(원본 12,13)
for sl in (69, 70, 71, 72):
    R(sl, [["(S/C #1 출고작업", "(S/C #1 → 29 피킹대  출고작업"]])
for sl in (73, 74):
    R(sl, [
        ["C/V #2 #3 → #21", "C/V #2 #3 → #27"],
        ["To : D0373(%DW851)=00/00/21", "To : D0373(%DW851)=00/00/27"],
        ["입출고대 #21 로 주행", "29 피킹대 #27 로 주행"],
        ["#21", "#27"],
        ["(S/C #1 출고작업", "(S/C #1 → 29 피킹대  출고작업"],
    ])
for sl in (75, 76):
    R(sl, [
        ["( 출고  : C/V # 14 ", "(S/C #1 → 29 피킹대  출고작업 ④ : C/V #14 "],
        ["피킹존 출고(동시에 입고 C/V 존재함))", "#27 → #28 → #29)"],
    ])

io.open("rules_CF.json", "w", encoding="utf-8").write(json.dumps(rules, ensure_ascii=False, indent=1))
print("rules:", len(rules), "subs:", sum(len(r["subs"]) for r in rules))
