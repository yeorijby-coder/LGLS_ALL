# -*- coding: utf-8 -*-
"""챕터 B(입출고대 #22 출고, 슬라이드 16~28) 다이어그램 치환 규칙 생성.

  17,18 ← 원본 27,28 (S/C 입고)  → S/C 출고 (랙 → 통로 C/V #2 #4)
  19,20 ← 원본 25,26 (통로 입고) → 통로 출고 (#4 → #3)
  21,22 ← 원본 23,24 (RGV 입고)  → RGV 출고 (#3 → 입출고대 #21)
  23,24 ← 원본 10,11 (입출고대 출고) : 제목만 챕터 형식으로

  주소 근거 : PlcAddressMap.xml 시나리오 2 (scen.json)
    통로 C/V #2  base(Event)=288
      UnloadComplete1 289 / LoadComplete1 290 / UnloadComplete2 291 / LoadComplete2 292
      #1 = RGV측, #2 = S/C측
    Ack base=1296 : 1297 / 1298 / 1299 / 1300
"""
import io, json

def mbit(a):
    return "M%03d.%d" % (a // 16, a % 16)

rules = []

def R(slide, subs):
    rules.append({"slide": slide, "subs": subs})

# ── 17 : S/C 반송 전반 (원본 27) ────────────────────────────────────────
R(17, [
    ["입고작업 ④", "출고작업 ①"],
    ["C/V #2 #4 → ", "랙 → C/V #2 #4"],          # 제목 뒷부분 '랙' 런은 아래에서 비움
    ["=00/00/04,  To : D0323(%DW771)=", "=랙 셀(좌우/Bay/Level),  To : D0323(%DW771)=00/00/04"],
    ["의  #4  에서  Load  완료 → 랙 셀로 주행", "랙 셀에서 Load 완료 → C/V #2 의 #4 로 주행"],
    ["From = 00/00/04 = C/V #2", "To = 00/00/04 = C/V #2"],
    ["(S/C측 픽업포트),  To = ", "(S/C측 하역포트),  From = "],
])

# ── 18 : S/C 반송 후반 (원본 28) ────────────────────────────────────────
R(18, [
    ["입고작업 ④", "출고작업 ①"],
    ["C/V #2 #4 → ", "랙 → C/V #2 #4"],
    ["From = 00/00/", "To = 00/00/"],
    ["랙 적치 완료", "통로 C/V 하역 완료"],
    ["입고작업 종료", "다음 : 통로 C/V 로 이송"],
])

# ── 19 : 통로 C/V 전반 (원본 25) : #3→#4 입고 → #4→#3 출고 ─────────────
#   S/C 가 #4 에 하역 → Load Complete #2 → ID Shift → #3 도착
sub19 = [
    ["입고작업 ③", "출고작업 ②"],
    ["#3 → #4 → S/C", "#4 → #3 → RGV"],
    ["픽업", "픽업"],                                   # 자리 유지(무해)
    # 도착 설명
    ["RGV", "S/C"],
    # Pallet Exist : #3(304) ↔ #4(305)
    ["%MX304", "%MX305"], ["%MX305", "%MX304"],
    [mbit(304), mbit(305)], [mbit(305), mbit(304)],
    ["Pallet Exist #3", "Pallet Exist #4"],
    ["Pallet Exist #4", "Pallet Exist #3"],
    # Load Complete #1(290) → #2(292), Ack 1298 → 1300
    ["%MX290", "%MX292"], [mbit(290), mbit(292)],
    ["%MX1298", "%MX1300"], [mbit(1298), mbit(1300)],
    ["Load Complete#1", "Load Complete#2"],
    ["Load Complete Ack#1", "Load Complete Ack#2"],
    # 방향
    ["는 입고대 방향 확인 후", "는 출고대 방향 확인 후"],
    ["* 입고 0, 출고 1", "* 입고 0, 출고 1"],
    ["%DB962)) “0”", "%DB962)) “1”"],
    ["%DB962) “0”", "%DB962) “1”"],
    ["* 0이 아닐 경우 변경", "* 1이 아닐 경우 변경"],
    # JOB NO : 최초 기록은 S/C측(R0012), ID Shift 후 RGV측(R0010)
    ["R0010~R0011 %RB20~%RB22", "R0012~R0013 %RB24~%RB26"],
    ["R0012~R0013 %RB24~%RB26", "R0010~R0011 %RB20~%RB22"],
    # 본문 포지션 표기
    ["#4  로", "#3 로"],
    ["#3 영역에서", "#4 영역에서"],
    ["#4  영역으로", "#3 영역으로"],
    ["#4 Pallet", "#3 Pallet"],
    ["입고 방향값  = 0", "출고 방향값 = 1"],
]
R(19, sub19)

# ── 20 : 통로 C/V 후반 (원본 26) : S/C Call → RGV Call ─────────────────
R(20, [
    ["입고작업 ③", "출고작업 ②"],
    ["#3 → #4 → S/C", "#4 → #3 → RGV"],
    ["S/C Call", "RGV Call"],
    ["S/C", "RGV"],
    # Unload Complete #2(291) → #1(289), Ack 1299 → 1297
    ["%MX291", "%MX289"], [mbit(291), mbit(289)],
    ["%MX1299", "%MX1297"], [mbit(1299), mbit(1297)],
    ["Unload Complete#2", "Unload Complete#1"],
    ["Unload Complete Ack#2", "Unload Complete Ack#1"],
    # Pallet Exist #4 → #3
    ["Pallet Exist #4", "Pallet Exist #3"],
    ["%MX305", "%MX304"], [mbit(305), mbit(304)],
    ["R0012~R0013 %RB24~%RB26", "R0010~R0011 %RB20~%RB22"],
    ["* 출고의 경우는 입고의 반대 순서대로 진행되면 됨", "* 입고의 경우는 출고의 반대 순서대로 진행되면 됨"],
])

# ── 21 : RGV 반송 전반 (원본 23) : From #3, To #21 ─────────────────────
R(21, [
    ["입고작업 ②", "출고작업 ③"],
    ["#21 → C/V #2 #3", "C/V #2 #3 → #21"],
    ["=00/00/21,  To : D0373(%DW851)=00/00/03", "=00/00/03,  To : D0373(%DW851)=00/00/21"],
    ["RGV : #21  에서  Load  완료 →  C/V #2 #3  으로 주행", "RGV : C/V #2 의 #3 에서 Load 완료 → 입출고대 #21 로 주행"],
    ["To = 00/00/03 = C/V #2", "From = 00/00/03 = C/V #2"],
])

# ── 22 : RGV 반송 후반 (원본 24) ───────────────────────────────────────
R(22, [
    ["입고작업 ②", "출고작업 ③"],
    ["#21 → C/V #2 #3", "C/V #2 #3 → #21"],
])

# ── 23,24 : 입출고대 출고 (원본 10,11) : 제목만 챕터 형식으로 ──────────
R(23, [["( 출고  : C/V # 11 )", "(S/C #1 출고작업 ④ : 입출고대 #21 → #22, C/V #11)"],
       ["출고 ", "S/C #1 출고작업 ④ : 입출고대 #21 → #22, C/V #11"],
       [": C/V # 11 )", ""]])
R(24, [["( 출고  : C/V # 11 )", "(S/C #1 출고작업 ④ : 입출고대 #21 → #22, C/V #11)"],
       ["출고 ", "S/C #1 출고작업 ④ : 입출고대 #21 → #22, C/V #11"],
       [": C/V # 11 )", ""]])

io.open("rules_B.json", "w", encoding="utf-8").write(json.dumps(rules, ensure_ascii=False, indent=1))
print("rules:", len(rules), "subs:", sum(len(r["subs"]) for r in rules))
