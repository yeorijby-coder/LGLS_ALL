-- [LGLS 2026-09-22] DEST_POS_DEF 현장 동기화 (사용자 지시)
--
--   이 표 하나가 운전 화면의 출발지/도착지 목록을 전부 만든다 :
--     · 수동지시(반자동) 창 - 출발지는 126,129 를 빼고, 도착지는 124,130 을 뺀 목록
--     · 작업정보 창 조회조건 - 전부
--     · C/V 상태창 도착지 콤보 - 전부
--   현장 표가 흐트러져 목록이 이상하게 보이면 이 스크립트로 사내 DB 와 같게 맞춘다.
--
--   ★ 하기 전에 ★
--     · 아래가 현재 사내(LGLS_MCS_IO) 내용 그대로다. 현장에 다른 창고(WH_TYP)나
--       추가 작업대가 있다면 지우지 말고 그 행을 이 목록에 먼저 보태고 돌린다.
--     · 돌리기 전 현재 내용을 백업 표로 떠 둔다(아래에서 자동으로 뜬다).
--     · 운전 화면은 창을 새로 열 때 이 표를 읽는다 - 창을 닫았다 열면 반영된다(재기동 불필요).
-- =====================================================================
USE LGLS_MCS_IO;
GO

SET NOCOUNT ON;

-- ── 0) 지금 내용 백업 (DEST_POS_DEF_BAK_YYYYMMDD) ─────────────────────
DECLARE @bak sysname = 'DEST_POS_DEF_BAK_' + CONVERT(varchar(8), GETDATE(), 112);
IF OBJECT_ID(@bak) IS NULL
BEGIN
    DECLARE @sql nvarchar(400) = N'SELECT * INTO ' + QUOTENAME(@bak) + N' FROM DEST_POS_DEF';
    EXEC sp_executesql @sql;
    PRINT '백업 표 생성 : ' + @bak;
END
ELSE
    PRINT '백업 표가 이미 있어 건너뜀 : ' + @bak;
GO

-- ── 1) 사내 DB 내용으로 교체 ──────────────────────────────────────────
BEGIN TRAN;

DELETE FROM DEST_POS_DEF;

INSERT INTO DEST_POS_DEF (TRACK_NO, MC_NO, GROUP_NO, WH_TYP, PRIORITY, RET_CNT, REMARKS) VALUES
  ('1024','124','IN','10',1,'0','IMS104 C/V#12 입고대 TR#24'),
  ('1030','130','IN','10',1,'0','IMS102 C/V#15 피킹입고 TR#30'),
  ('1022','122','OUT','10',1,'0','IMS101 C/V#11 입출고대 TR#22'),
  ('1026','126','OUT','10',1,'0','IMS103 C/V#13 출고대 TR#26'),
  ('1029','129','OUT','10',1,'0','IMS102 C/V#14 피킹출고 TR#29'),
  ('0901','901','SC','10',1,'0','S/C#1'),
  ('0902','902','SC','10',1,'0','S/C#2'),
  ('0903','903','SC','10',1,'0','S/C#3'),
  ('0904','904','SC','10',1,'0','S/C#4'),
  ('0905','905','SC','10',1,'0','S/C#5');

-- 확인 후 문제가 없으면 COMMIT, 이상하면 ROLLBACK 으로 바꿔 돌린다.
COMMIT;
GO

-- ── 2) 결과 확인 ─────────────────────────────────────────────────────
SELECT TRACK_NO, MC_NO, GROUP_NO, WH_TYP, PRIORITY, RET_CNT, REMARKS
  FROM DEST_POS_DEF
 ORDER BY GROUP_NO, MC_NO;
GO

-- 기대 결과
--   IN  : 124(입고대)  130(피킹입고)
--   OUT : 122(입출고대) 126(출고대) 129(피킹출고)
--   SC  : 901 ~ 905
--   → 수동지시 창 출발지 = 124,130,122,901~905 / 도착지 = 122,126,129,901~905
